"""Generates supabase/seed.sql from the cleaned master data (src/edition-3/data.json).
Run from the repository root:  python3 supabase/seed/gen_seed.py"""
import json, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
d = json.loads((root / 'src/edition-3/data.json').read_text(encoding='utf-8'))
q = lambda s: "'" + str(s).replace("'", "''") + "'"
out = ['-- GENERATED by supabase/seed/gen_seed.py. Do not edit by hand.', 'begin;']
out.append('insert into colors(code,ar) values\n' + ',\n'.join(f"({q(c['code'])},{q(c['ar'])})" for c in d['colors']) + ';')
out.append('insert into models(code,name) values\n' + ',\n'.join(f"({q(m['code'])},{q(m['name'])})" for m in d['models']) + ';')
out.append('insert into skus(id,model,color,size,min_alert) values\n' + ',\n'.join(f"({q(k['id'])},{q(k['m'])},{q(k['c'])},{q(k['s'])},{int(k.get('min') or 0)})" for k in d['skus']) + ';')
op = [k for k in d['skus'] if (k.get('open') or 0) > 0]
out.append(f"insert into moves(move_date,sku,qty,from_loc,to_loc,type,doc,by,note) values\n" + ',\n'.join(
    f"({q(d['asOf'])},{q(k['id'])},{int(k['open'])},'EXT_OPEN','READY','OPN','OPN-0001','system','opening balance (physical count {d['asOf']})')" for k in op) + ';')
out.append("insert into doc_seq(type,n) values ('OPN',1) on conflict (type) do nothing;")
for i, p in enumerate(d['pickups'], 1):
    out.append(f"insert into pickups(id,label,pickup_date,channel,source) values ({q('P%d' % i)},{q(p['label'])},{q(d['today'])},'VENDOOR','Vendoor file 2026-11-02');")
    rows = []
    for o in p['orders']:
        arr = 'array[' + ','.join(q(s) for s in o['lines']) + ']::text[]'
        ty = 'exchange' if 'استبدال' in str(o['type']) else 'new'
        rows.append(f"({q(o['ref'])},{q(o['wb'])},{q(ty)},{q(o['gov'])},{float(o['total'] or 0)},{arr},{q('P%d' % i)})")
    out.append('insert into orders(ref,waybill,type,gov,total,lines,pickup_id) values\n' + ',\n'.join(rows) + ';')
sup = [
 ('FLY','Carrier flyer','piece',1,'',300,'{"kind":"order","qty":1}',2000),
 ('PKS','Packaging S','piece',1,'',100,'{"kind":"range","qty":1,"from":1,"to":2}',600),
 ('PKM','Packaging M','piece',1,'',100,'{"kind":"range","qty":1,"from":3,"to":5}',600),
 ('PKL','Packaging L','piece',1,'',100,'{"kind":"range","qty":1,"from":6,"to":0}',300),
 ('CUP','Bra cups','cup',24,'bag',200,'{"kind":"pieces","qty":2,"model":"BR1"}',960)]
out.append('insert into supplies(id,name,unit,pack,pack_name,min_alert,rule) values\n' + ',\n'.join(f"({q(s[0])},{q(s[1])},{q(s[2])},{s[3]},{q(s[4])},{s[5]},{q(s[6])}::jsonb)" for s in sup) + ';')
out.append("insert into supply_log(log_date,item,qty,kind,why,by) values\n" + ',\n'.join(f"({q(d['asOf'])},{q(s[0])},{s[7]},'open','demo opening balance, replace with a count','system')" for s in sup) + ';')
out.append('commit;')
(root / 'supabase/seed.sql').write_text('\n'.join(out) + '\n', encoding='utf-8')
print('seed.sql', len(op), 'opening moves,', sum(len(p['orders']) for p in d['pickups']), 'orders')
